import { useEffect, useLayoutEffect, useRef, useState } from "react";
import { createDeck, type DeckApi, type DeckSnapshot } from "@/kit/runtime/deck";
import { REGISTRY } from "@/slides/registry";
import Slide, { type SlideDef, type SlideType, type Transition } from "./Slide";
import Hud, { KeyList } from "./Hud";
import Presenter from "./Presenter";

export type { SlideDef, SlideProps, SlideType, Transition } from "./Slide";

/** "static" is the prerender (no window): the same markup as "deck", nothing mounted. */
export type DeckViewMode = "deck" | "presenter" | "print" | "static";

function detectMode(): DeckViewMode {
  if (typeof window === "undefined") return "static";
  const q = new URLSearchParams(window.location.search);
  if (q.has("print")) return "print";
  if (q.has("presenter")) return "presenter";
  return "deck";
}

// useLayoutEffect warns on the server; the prerender never runs effects anyway
const useIsoLayoutEffect = typeof window === "undefined" ? useEffect : useLayoutEffect;

/**
 * Mounts the runtime on its stage and renders one <Slide> per SlideDef from the slide type registry
 * (src/slides/registry.ts, generated by sync-kit.sh). The runtime owns the classes (`.in`, `.is-current`);
 * React passes each slide component `{ data, step }`.
 */
export default function Deck({
  id,
  slides,
  transition = "fade",
  mode: forced,
  registry = REGISTRY,
}: {
  id: string;
  slides: SlideDef[];
  transition?: Transition;
  mode?: DeckViewMode;
  registry?: Record<string, SlideType>;
}) {
  const [mode] = useState<DeckViewMode>(() => forced ?? detectMode());
  const stage = useRef<HTMLDivElement>(null);
  const api = useRef<DeckApi | null>(null);
  const [snap, setSnap] = useState<DeckSnapshot>({ slide: 0, step: 0, total: slides.length, steps: 0, jump: "", startedAt: null });

  const stepsOf = (def: SlideDef) => {
    const t = registry[def.type];
    return t ? Math.max(0, t.steps(def.data) | 0) : 0;
  };

  useEffect(() => {
    if (mode === "static" || !stage.current) return;
    const d = createDeck({ id, root: stage.current, mode: mode === "print" ? "print" : mode === "presenter" ? "presenter" : "deck", onChange: setSnap });
    api.current = d;
    return () => { d.destroy(); api.current = null; };
  }, [id, mode]);

  // after every render: re-gate new nodes, refit (the presenter panes may have changed size)
  useIsoLayoutEffect(() => { api.current?.sync(); });

  const stepFor = (i: number, def: SlideDef) =>
    mode === "print" ? stepsOf(def) : i === snap.slide ? snap.step : i < snap.slide ? stepsOf(def) : 0;

  const section = (def: SlideDef, i: number, step: number, className?: string) => {
    const t = registry[def.type];
    if (!t && typeof window !== "undefined") console.error(`deck: no slide type "${def.type}" (slide ${i + 1}, ${def.id}); run sync-kit.sh --slides ${def.type}`);
    return (
      <Slide key={def.id} id={def.id} type={def.type} index={i} steps={stepsOf(def)} transition={def.transition ?? transition} className={className}>
        {t ? <t.Component data={def.data} step={step} /> : <p style={{ padding: 112 }}>Tip de slide lipsă: {def.type}</p>}
      </Slide>
    );
  };

  const stageEl = (
    <div className="deck-viewport" data-deck-main>
      <div className="deck-stage" ref={stage}>
        {slides.map((def, i) => section(def, i, stepFor(i, def)))}
      </div>
    </div>
  );

  if (mode === "presenter") {
    const n = slides[snap.slide + 1];
    return (
      <Presenter
        current={stageEl}
        next={n ? section(n, snap.slide + 1, stepsOf(n), "is-current") : null}
        notes={slides[snap.slide]?.notes}
        slide={snap.slide}
        total={slides.length}
        step={snap.step}
        steps={stepsOf(slides[snap.slide])}
        startedAt={snap.startedAt}
      />
    );
  }

  return (
    <>
      {stageEl}
      {mode !== "print" && (
        <>
          <Hud slide={snap.slide} total={slides.length} jump={snap.jump} />
          <KeyList />
        </>
      )}
    </>
  );
}
