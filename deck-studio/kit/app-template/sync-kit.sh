#!/usr/bin/env bash
# Copies the deck-studio kit into an app made from kit/app-template. Safe to re-run (re-sync after a kit fix).
#   kit/app-template/sync-kit.sh <app-dir> [--slides title,cascade-list]
# Layout inside the app:
#   src/kit/runtime/{deck.ts,prerender.mjs}   src/kit/react/*.tsx   src/styles/{tokens,deck}.css
#   src/slides/<type>/ (code, css, data.example.ts, preview.tsx; slide.md stays in the skill)
#   public/<asset>  example media from kit/slides/<type>/public/, written only when missing
#   src/slides/registry.ts    generated: every type folder present in src/slides
#   src/preview-deck.tsx      generated: one slide per type from data.example.ts (?preview),
#                             plus each type's preview.tsx variants (?preview=<type>)
# Written only when missing (the app owns them after the first copy): src/styles/tokens.css, src/deck.tsx.
set -euo pipefail
KIT="$(cd "$(dirname "$0")/.." && pwd)"
[ -d "$KIT/runtime" ] || { echo "run sync-kit.sh from the skill (kit/app-template/), not from a copy inside the app" >&2; exit 1; }
APP=""; SLIDES=""
while [ $# -gt 0 ]; do
  case "$1" in
    --slides) SLIDES="${2:?--slides needs a comma list}"; shift 2 ;;
    --slides=*) SLIDES="${1#--slides=}"; shift ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    *) APP="$1"; shift ;;
  esac
done
[ -n "$APP" ] || { echo "usage: sync-kit.sh <app-dir> [--slides a,b]" >&2; exit 1; }
[ -f "$APP/package.json" ] || { echo "$APP has no package.json: copy kit/app-template first (SKILL.md Phase 4)" >&2; exit 1; }

mkdir -p "$APP/src/kit/runtime" "$APP/src/kit/react" "$APP/src/styles" "$APP/src/slides"
cp "$KIT/runtime/deck.ts" "$KIT/runtime/prerender.mjs" "$APP/src/kit/runtime/"
cp "$KIT"/react/*.tsx "$APP/src/kit/react/"
cp "$KIT/css/deck.css" "$APP/src/styles/deck.css"
[ -f "$APP/src/styles/tokens.css" ] || cp "$KIT/css/tokens.css" "$APP/src/styles/tokens.css"
[ -f "$APP/src/deck.tsx" ] || cp "$KIT/app-template/src/deck.tsx" "$APP/src/deck.tsx"
echo "kit: runtime, react, styles"

for s in ${SLIDES//,/ }; do
  [ -n "$s" ] || continue
  [ -d "$KIT/slides/$s" ] || { echo "no slide type kit/slides/$s (see kit/slides/INDEX.md)" >&2; exit 1; }
  mkdir -p "$APP/src/slides/$s"
  find "$KIT/slides/$s" -maxdepth 1 -type f ! -name '*.md' -exec cp {} "$APP/src/slides/$s/" \;
  # example assets a type ships (kit/slides/<type>/public/*) land in the app's public/, written only when missing
  if [ -d "$KIT/slides/$s/public" ]; then
    mkdir -p "$APP/public"
    for f in "$KIT/slides/$s/public"/*; do [ -f "$f" ] || continue; [ -f "$APP/public/$(basename "$f")" ] || cp "$f" "$APP/public/"; done
  fi
  echo "slide: $s -> src/slides/$s"
done

# every type folder in the app, in catalogue order (INDEX.md), then any others alphabetically
ORDER=$(grep -oE '^\| `[a-z0-9-]+`' "$KIT/slides/INDEX.md" | sed -E 's/^\| `([a-z0-9-]+)`/\1/')
PRESENT=$(find "$APP/src/slides" -mindepth 1 -maxdepth 1 -type d -exec basename {} \; | sort)
TYPES=$( { for t in $ORDER; do echo "$PRESENT" | grep -qx "$t" && echo "$t"; done; for t in $PRESENT; do echo "$ORDER" | grep -qx "$t" || echo "$t"; done; } )
pascal() { echo "$1" | awk -F- '{ for (i = 1; i <= NF; i++) printf "%s%s", toupper(substr($i, 1, 1)), substr($i, 2) }'; }
ident() { echo "$1" | tr '-' '_'; }

REG="$APP/src/slides/registry.ts"
{
  echo "/* generated by sync-kit.sh: every slide type in src/slides. Do not edit; re-run sync-kit.sh. */"
  echo 'import type { SlideType } from "@/kit/react/Slide";'
  for t in $TYPES; do
    P=$(pascal "$t")
    [ -f "$APP/src/slides/$t/$P.tsx" ] || { echo "src/slides/$t has no $P.tsx" >&2; exit 1; }
    echo "import * as t_$(ident "$t") from \"@/slides/$t/$P\";"
  done
  echo ""
  echo "export const REGISTRY: Record<string, SlideType> = {"
  for t in $TYPES; do echo "  \"$t\": { Component: t_$(ident "$t").default, steps: t_$(ident "$t").steps },"; done
  echo "};"
} > "$REG"

PV="$APP/src/preview-deck.tsx"
{
  echo "/* generated by sync-kit.sh: the dev preview deck. ?preview = one slide per type from data.example.ts,"
  echo "   ?preview=<type> = that type's preview.tsx variants. Do not edit; re-run sync-kit.sh. */"
  echo 'import type { SlideDef } from "@/kit/react/Slide";'
  for t in $TYPES; do
    [ -f "$APP/src/slides/$t/data.example.ts" ] && echo "import * as ex_$(ident "$t") from \"@/slides/$t/data.example\";"
    [ -f "$APP/src/slides/$t/preview.tsx" ] && echo "import { variants as pv_$(ident "$t") } from \"@/slides/$t/preview\";"
  done
  echo ""
  echo "export const PREVIEW: SlideDef[] = ["
  for t in $TYPES; do
    [ -f "$APP/src/slides/$t/data.example.ts" ] && echo "  { id: \"preview-$t\", type: \"$t\", data: ex_$(ident "$t").example, notes: ex_$(ident "$t").notes },"
  done
  echo "];"
  echo ""
  echo "export const VARIANTS: Record<string, SlideDef[]> = {"
  for t in $TYPES; do [ -f "$APP/src/slides/$t/preview.tsx" ] && echo "  \"$t\": pv_$(ident "$t"),"; done
  echo "};"
  echo ""
  echo "export function previewDeck(which: string | null): SlideDef[] {"
  echo "  return which && VARIANTS[which] ? VARIANTS[which] : PREVIEW;"
  echo "}"
} > "$PV"
echo "generated: src/slides/registry.ts, src/preview-deck.tsx ($(echo $TYPES | wc -w | tr -d ' ') types)"
echo "synced into $APP"
